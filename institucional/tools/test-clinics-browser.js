async page => {
  const errors = [], failed = [], external = [], checks = [];
  const origin = 'http://127.0.0.1:8176';
  const url = origin + '/servicos/clinicas-de-estetica.html';
  const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if(r.status()>=400)failed.push(r.status()+' '+r.url());});
  page.on('request', r => {if(/^https?:/.test(r.url())&&!r.url().startsWith(origin))external.push(r.url());});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(url);
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished)));
  assert(await page.getByRole('heading',{level:1}).count()===1,'Um H1 e conteúdo carregado');
  assert(await page.locator('#quem-conduz .clinic-team-person').count()===2,'Dois responsáveis apresentados');
  assert((await page.locator('#quem-conduz').innerText()).includes('Stanley Batista')&&(await page.locator('#quem-conduz').innerText()).includes('Guilherme Domério'),'Equipe com nomes do site institucional');
  assert(await page.locator('#quem-conduz').evaluate(e=>e.previousElementSibling.classList.contains('process')&&e.nextElementSibling.id==='hub'),'Equipe entre processo e Hub');
  assert((await page.locator('.demo-summary h4').innerText()).includes('R$ 3.000')&&(await page.locator('.demo-summary h4').innerText()).includes('R$ 30,00'),'Resumo com 3 mil e custo médio recalculado');
  assert(JSON.stringify(await page.locator('.demo-sales-funnel dd').allTextContents())===JSON.stringify(['100','30','24','8']),'Funil consistente: 100 contatos, 30 agendamentos, 24 presenças e 8 vendas');
  assert(await page.locator('.demo-bars b').evaluateAll(es=>es.reduce((sum,e)=>sum+Number(e.textContent),0))===25,'Gráfico de 7 dias soma 25 contatos');
  assert(JSON.stringify(await page.locator('.demo-economics-grid strong').allTextContents())===JSON.stringify(['R$ 900','R$ 7.200','2,4×']),'Ticket, receita e proporção coerentes com oito vendas');
  await page.locator('.demo-economics summary').click();
  assert((await page.locator('.demo-economics details').innerText()).includes('R$ 375')&&(await page.locator('.demo-economics details').innerText()).includes('não desconta gestão'),'Premissas e exclusões da receita disponíveis');
  await page.locator('.demo-economics summary').click();
  assert(await page.locator('.clinic-portrait').getAttribute('src')==='../assets/img/clinicas/gestora-clinica-premium.webp','Retrato original gerado aplicado na abertura');
  assert(await page.locator('.clinic-room img').getAttribute('src')==='../assets/img/clinicas/recepcao-clinica-premium.webp','Recepção original gerada aplicada na abertura');
  assert(await page.locator('.trust,.marquee,.visual-note,.clinic-hero-visual figcaption').count()===0,'Etiquetas e legendas redundantes removidas');
  assert((await page.locator('.demo-profile').innerText()).includes('Serena'),'Painel identificado com a clínica Serena');
  assert(await page.locator('.demo-tabs').getAttribute('aria-orientation')==='horizontal','Painel com navegação superior');
  await page.locator('.faq-item summary').first().click();
  assert((await page.locator('.faq-item').first().innerText()).includes('Sim. A Bādon planeja'),'FAQ confirma a operação de anúncios');
  await page.locator('.faq-item summary').first().click();
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  assert(await page.locator('.site-screen img').getAttribute('src')==='../assets/img/clinicas/site-serena-tela.webp','Mockup usa a tela do site Serena');
  await page.screenshot({path:'output/clinicas-20261104/hero-desktop.png'});
  await page.getByRole('tab',{name:'CRM',exact:false}).click();
  await page.locator('#advance-lead').click();
  assert((await page.locator('#demo-status').innerText()).includes('Agendamentos'),'CRM avança para agendamento');
  await page.locator('#advance-lead').click();
  await page.locator('#advance-lead').click();
  assert(await page.locator('#advance-lead').isDisabled(),'CRM encerra em vendas');
  await page.getByRole('button',{name:'Lista',exact:true}).click();
  assert((await page.locator('.demo-table').innerText()).includes('Vendas'),'CRM em lista conserva a etapa');
  await page.locator('#reset-crm').click();
  assert((await page.locator('.demo-table').innerText()).includes('Contatos'),'Reinício restaura o contato');
  await page.locator('#tab-criativos').click();
  const investments=await page.locator('.creative-card > div > small:last-child').allTextContents();
  assert(investments.length===3&&investments.some(v=>v.includes('1.020,00'))&&investments.some(v=>v.includes('1.080,00'))&&investments.some(v=>v.includes('900,00')),'Peças somam R$ 3.000 de investimento');
  assert((await page.locator('.creative-card').first().innerText()).includes('25,50'),'Custo por contato do melhor criativo recalculado');
  assert(await page.locator('.creative-metrics span:first-child b').evaluateAll(es=>es.reduce((sum,e)=>sum+Number(e.textContent),0))===100,'Criativos somam 100 contatos em 30 dias');
  await page.locator('#demo-period').selectOption('7');
  assert(await page.locator('.creative-metrics span:first-child b').evaluateAll(es=>es.reduce((sum,e)=>sum+Number(e.textContent),0))===25,'Criativos de 7 dias conferem com o gráfico');
  assert(await page.locator('.creative-card > div > small:last-child').evaluateAll(es=>es.reduce((sum,e)=>sum+Number(e.textContent.replace(/[^0-9,]/g,'').replace(',','.')),0))===750,'Investimento de 7 dias soma R$ 750');
  await page.locator('#demo-sort').selectOption('contatos');
  assert((await page.locator('.creative-card').first().innerText()).includes('10'),'Filtro recalcula os números simulados');
  await page.locator('.creative-card').first().click();
  await page.locator('#demo-approve').click();
  assert((await page.locator('#demo-status').innerText()).includes('Não foi enviada'),'Aprovação local não simula envio real');
  await page.locator('#demo-period').selectOption('30');
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished)));
  await page.locator('#hub-demo').screenshot({path:'output/clinicas-20261104/hub-desktop.png'});
  await page.locator('#tab-roteiros').click();
  await page.locator('.script-list summary').first().click();
  assert(await page.locator('.script-list details').first().getAttribute('open')!==null,'Roteiro expande com orientações');
  await page.locator('#tab-plano').click();
  assert(await page.getByRole('progressbar').getAttribute('aria-valuenow')==='1','Plano tem progresso acessível');
  await page.locator('#tab-plano').focus(); await page.keyboard.press('Home');
  assert(await page.locator('#tab-visao').getAttribute('aria-selected')==='true','Teclado navega entre abas');
  await page.locator('#demo-tour').click();
  await page.waitForFunction(()=>document.querySelector('#tab-crm').getAttribute('aria-selected')==='true',{},{timeout:7000});
  await page.locator('#demo-tour').click();
  assert(await page.locator('#demo-tour').getAttribute('aria-pressed')==='false','Tour iniciado pelo visitante e pausável');
  await page.locator('#open-clinic-preview').click();
  await page.frameLocator('#clinic-preview iframe').locator('body').waitFor();
  await page.waitForFunction(()=>!!document.querySelector('#clinic-preview[open]'));
  assert(await page.locator('#clinic-preview').isVisible(),'Prévia abre dentro da página');
  const frame=page.frames().find(f=>f.url().includes('/serena/index.html'));
  assert(!!frame,'Prévia carregou o site Serena');
  await frame.waitForFunction(()=>document.body.innerText.length>100);
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#clinic-preview').isVisible()),'Escape fecha o modal');
  assert(await page.locator('#open-clinic-preview').evaluate(e=>e===document.activeElement),'Modal devolve o foco');
  for(const width of [320,390,768,1024,1440]){
    await page.setViewportSize({width,height:900});
    for(const tab of ['visao','crm','criativos','roteiros','plano']){
      await page.locator('#tab-'+tab).click();
      const dims=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth,container:document.querySelector('#hub-demo').getBoundingClientRect().width,panel:document.querySelector('#demo-panel').getBoundingClientRect().width}));
      assert(dims.page<=dims.viewport&&dims.panel<=dims.container+1,`Layout ${width}px / ${tab} sem vazamento ou corte do painel`);
    }
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('#tab-criativos').click();
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished)));
  await page.locator('#hub-demo').screenshot({path:'output/clinicas-20261104/hub-mobile.png'});
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'output/clinicas-20261104/hero-mobile.png'});
  await page.locator('.mobile-toggle').click();
  assert(await page.locator('.mobile-toggle').getAttribute('aria-expanded')==='true','Menu móvel abre');
  await page.keyboard.press('Escape');
  assert(await page.locator('.mobile-toggle').getAttribute('aria-expanded')==='false','Menu móvel fecha com Escape');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload();
  assert(await page.locator('.clinic-hero-visual').evaluate(e=>getComputedStyle(e).animationName)==='none','Movimento reduzido respeitado');
  await page.locator('.webseo').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/clinicas-20261104/site-mobile.png'});
  const broken=await page.evaluate(()=>[...document.images].filter(i=>i.complete&&!i.naturalWidth).map(i=>i.src));
  assert(broken.length===0,'Imagens carregadas sem falha');
  assert(errors.length===0,'Sem erros JavaScript');
  assert(failed.length===0,'Sem requisições HTTP com erro');
  assert(external.length===0,'Sem requisições externas na navegação e demonstração');
  const clinicNetwork={errors:[...errors],failed:[...failed],external:[...external]};
  await page.goto(origin+'/');
  await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
  await page.locator('details.services-menu summary').click();
  await page.getByRole('link',{name:'Aquisição para clínicas',exact:true}).click();
  assert(page.url()===url,'Novo serviço acessível pelo menu da página inicial');
  const nojs=await page.context().browser().newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const basic=await nojs.newPage();await basic.goto(url);
  assert(await basic.getByRole('heading',{level:1}).isVisible(),'Conteúdo e CTAs disponíveis sem JavaScript');
  await nojs.close();
  return {checks,clinicNetwork};
}
