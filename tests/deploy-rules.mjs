import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const account = fs.mkdtempSync(path.join(os.tmpdir(), 'badon-rules-'));
const publicDir = path.join(account, 'public_html');
fs.mkdirSync(publicDir);
const original = '# cPanel PHP handler\nAddType text/plain .test\n# BEGIN WordPress\nRewriteRule . /index.php [L]\n# END WordPress\n# BEGIN BADON CUSTOM 404\nOld rule\n# END BADON CUSTOM 404\n';
fs.writeFileSync(path.join(publicDir, '.htaccess'), original);
fs.writeFileSync(path.join(publicDir, 'preserve.txt'), 'KEEP');
const run = () => execFileSync('/bin/bash', ['deploy/install-rules.sh'], {env: {...process.env, BADON_ACCOUNT_DIR: account}});
run();
const rules = fs.readFileSync(path.join(publicDir, '.htaccess'), 'utf8');
assert.ok(rules.includes('# cPanel PHP handler'));
assert.ok(!rules.includes('# BEGIN WordPress') && !rules.includes('Old rule'));
const backupRoot = path.join(account, 'badon-site-backups');
const firstBackup = fs.readdirSync(backupRoot)[0];
assert.equal(fs.readFileSync(path.join(backupRoot, firstBackup, 'htaccess.before'), 'utf8'), original);
run();
assert.equal(fs.readFileSync(path.join(publicDir, '.htaccess'), 'utf8'), rules);
assert.equal(fs.readFileSync(path.join(publicDir, 'preserve.txt'), 'utf8'), 'KEEP');
assert.deepEqual(fs.readdirSync(publicDir).sort(), ['.htaccess', 'preserve.txt']);
fs.writeFileSync(path.join(publicDir, '.htaccess'), '# BEGIN WordPress\nIncomplete block\n');
assert.throws(run);
assert.equal(fs.readFileSync(path.join(publicDir, '.htaccess'), 'utf8'), '# BEGIN WordPress\nIncomplete block\n');
console.log('OK: rules-only deploy, private backup, cPanel preserved, WordPress removed, idempotence and fail-closed merge.');
