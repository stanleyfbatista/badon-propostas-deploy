import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'institucional/guias/50-ganchos');
const target=path.join(root,'public/presentes/50-ganchos');
const data=JSON.parse(fs.readFileSync(path.join(target,'ganchos-data.json'),'utf8'));
assert.equal(data.hooks.length,50);
assert.equal(new Set(data.hooks.map(h=>h.numero)).size,50);
assert.equal(data.prompts.length,3);
const html=fs.readFileSync(path.join(target,'index.html'),'utf8');
assert.equal((html.match(/class="hook"/g)||[]).length,50);
assert.match(html,/noindex, follow/);
assert.match(html,/presentes\/50-ganchos\//);
assert.equal((html.match(/download="Guia-50-Ganchos-Badon.pdf"/g)||[]).length,1,'Download somente no final');
assert(html.indexOf('id="baixar-guia"')>html.indexOf('id="conversar"'),'PDF depois do fechamento');
assert.match(html,/<div class="hero-actions"><a class="button primary" href="#biblioteca">Explorar os 50 ganchos/);
assert(!html.includes('application/ld+json'), 'Não é artigo de blog');
for(const file of fs.readdirSync(target)) assert.deepEqual(fs.readFileSync(path.join(target,file)),fs.readFileSync(path.join(source,file)),file);
const account=fs.mkdtempSync(path.join(os.tmpdir(),'badon-hooks-test-'));
const web=path.join(account,'public_html');fs.mkdirSync(web);
fs.writeFileSync(path.join(web,'index.html'),'site original');
const run=()=>spawnSync('bash',[path.join(root,'deploy/publish-hooks-guide.sh')],{env:{...process.env,BADON_ACCOUNT_DIR:account},encoding:'utf8'});
assert.equal(run().status,0,'Primeira publicação em fixture');
assert.equal(fs.statSync(path.join(web,'presentes')).mode&0o777,0o755);
const published=path.join(web,'presentes/50-ganchos');
assert.equal(fs.statSync(path.join(published,'index.html')).mode&0o777,0o644);
assert.equal(run().status,0,'Segunda publicação e backup');
assert.equal(fs.readFileSync(path.join(web,'index.html'),'utf8'),'site original');
const backups=path.join(account,'badon-site-backups');
assert(fs.readdirSync(backups).some(d=>fs.existsSync(path.join(backups,d,'index.html'))));
fs.renameSync(path.join(published,'guia.js'),path.join(account,'fixture-guia.js'));
fs.symlinkSync(path.join(account,'fixture-guia.js'),path.join(published,'guia.js'));
assert.notEqual(run().status,0,'Destino symlink deve ser recusado');
console.log('50 ganchos; 3 prompts; fontes/exportação idênticas; publicação isolada, backup, permissões e recusa de symlink OK. Fixture:',account);
