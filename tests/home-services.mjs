import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('public/index.html');
const section=html.slice(html.indexOf('<section class="panel dark-panel services"'),html.indexOf('<section class="team'));
assert.equal((section.match(/class="home-service-card"/g)||[]).length,4);
assert.equal((section.match(/class="home-service-contact"/g)||[]).length,4);
assert.doesNotMatch(section,/service-tabs|auto-tabs|service-direct-links|ILUSTRAÇÃO DO SERVIÇO|\shidden\b|role="tabpanel"/);
for(const slug of ['trafego-pago','sites','google-meu-negocio','identidade-visual'])assert.ok(section.includes('href="servicos/'+slug+'.html"'));
for(const [,src] of section.matchAll(/src="([^"]+)"/g))assert.ok(fs.existsSync(path.join(root,'public',src)),src);
const css=read('public/assets/css/home-services.css');
assert.match(css,/repeat\(2,minmax\(0,1fr\)\)/);
assert.match(css,/@media\(max-width:800px\)/);
assert.match(css,/grid-template-columns:1fr/);
assert.match(css,/prefers-reduced-motion/);
assert.match(css,/:focus-visible/);
assert.doesNotMatch(read('public/assets/js/main.js'),/showTab|stopAuto|serviceAnimation|auto-tabs/);
for(const file of ['index.html','assets/css/home-services.css','assets/js/main.js'])assert.ok(read('deploy/publish-home-navigation.sh').includes(file));
console.log('PASS: quatro serviços visíveis, imagens locais, oito CTAs, sem abas, teclado e movimento reduzido.');
