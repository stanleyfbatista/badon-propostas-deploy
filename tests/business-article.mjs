import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const root = path.resolve(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/blog/cara-de-empresa-grande.html'), 'utf8');
const ids = ['identidade','email','site','catalogo','fotos','proposta','avaliacoes','atendimento','conversar'];
for (const id of ids) {
  assert.equal((html.match(new RegExp('id="' + id + '"', 'g')) || []).length, 1);
  assert.ok(html.includes('href="#' + id + '"'));
}
assert.equal((html.match(/class="business-perception"/g) || []).length, 8);
assert.equal((html.match(/rel="canonical"/g) || []).length, 1);
assert.ok(html.includes('content="index, follow"'));
assert.ok(html.includes('property="og:image"'));
const structured = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(structured['@type'], 'BlogPosting');
assert.equal(structured.author['@type'],'Person');
assert.equal(structured.author.name,'Stanley Batista');
assert.doesNotMatch(html, /min de leitura/);
const articleCard = fs.readFileSync(path.join(root,'public/blog/index.html'),'utf8').split('data-category="Presença profissional"')[1].split('</article>')[0];
assert.doesNotMatch(articleCard, /min de leitura/);
assert.match(html, /class="business-author-photo" src="\.\.\/assets\/img\/hero-stanley.webp" alt="Stanley Batista" width="42" height="42"/);
assert.doesNotMatch(html, /Quero melhorar minha apresentação|Redação Bādon/);
const opening = html.match(/<div class="business-jump">([\s\S]*?)<\/div>/)[1];
assert.equal((opening.match(/<a /g)||[]).length,1);
assert.match(opening,/href="#identidade"/);
assert.match(opening,/Ler os 8 pontos/);
assert.equal(structured.mainEntityOfPage, 'https://produtorabadon.com/blog/cara-de-empresa-grande');
assert.ok(html.includes('rel="canonical" href="' + structured.mainEntityOfPage + '"'));
assert.ok(html.includes('property="og:url" content="' + structured.mainEntityOfPage + '"'));
assert.doesNotMatch(html, /mais barato|id="checklist"|Birra Sob Controle|juliana-macbook/);
assert.match(html, /O que tudo isso tem em comum/);
assert.match(html, /Imagem gerada que finge ser o seu ambiente quebra a confiança/);
assert.match(html, /Exemplo de resposta\. Use apenas um prazo que consiga cumprir\./);
assert.ok(html.indexOf('Seu trabalho é bom. Sua apresentação acompanha?') > html.indexOf('id="proposta"'));
assert.ok(html.indexOf('Seu trabalho é bom. Sua apresentação acompanha?') < html.indexOf('id="avaliacoes"'));
assert.match(html, /business-laptop/);
assert.match(html, /business-phone/);
for (const name of ['desktop','mobile']) assert.ok(fs.statSync(path.join(root, 'public/assets/img/blog/badon-site-' + name + '.jpg')).size > 1000);
const sitemap = fs.readFileSync(path.join(root,'public/sitemap.xml'),'utf8');
assert.match(sitemap, /blog\/cara-de-empresa-grande<\/loc>/);
assert.doesNotMatch(sitemap, /cara-de-empresa-grande\.html/);
for (const [,href] of html.matchAll(/href="(https:\/\/wa.me\/[^"]+)"/g)) {
  const url = new URL(href);
  assert.equal(url.pathname, '/5519983256292');
  assert.match(url.searchParams.get('text'), /Stanley.*Cara de empresa grande/);
}
assert.equal((html.match(/https:\/\/wa.me\//g) || []).length, 4);
for (const [id,label,intent] of [['identidade','Quero fazer minha identidade visual','identidade visual'],['site','Quero fazer meu site','quero fazer meu site'],['conversar','Quero ajuda com minha marca','ajuda com minha marca']]) {
  const section = html.split('id="'+id+'"')[1].split('</section>')[0];
  const links = [...section.matchAll(/href="(https:\/\/wa.me\/[^\"]+)"[^>]*>([^<]+)<\/a>/g)];
  const match = links.find(link=>link[2]===label);
  assert.ok(match, 'CTA ausente: '+id);
  assert.ok(new URL(match[1]).searchParams.get('text').includes(intent));
}
assert.doesNotMatch(html, /fbq\(|gtag\(|googletagmanager|connect.facebook|<iframe|<form/);
const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'badon-article-'));
for (const dir of ['assets/css','assets/js','assets/img/blog','blog']) fs.mkdirSync(path.join(fixture,'public_html',dir),{recursive:true});
fs.writeFileSync(path.join(fixture,'public_html/blog/index.html'),'previous-blog');
fs.writeFileSync(path.join(fixture,'public_html/.htaccess'),'routing-sentinel');
fs.writeFileSync(path.join(fixture,'public_html/unrelated.html'),'unrelated-sentinel');
const publish = () => execFileSync('bash',[path.join(root,'deploy/publish-business-article.sh')],{env:{...process.env,BADON_ACCOUNT_DIR:fixture}});
publish();
const backups = fs.readdirSync(path.join(fixture,'badon-site-backups'));
assert.equal(backups.length,1);
assert.equal(fs.readFileSync(path.join(fixture,'badon-site-backups',backups[0],'blog/index.html'),'utf8'),'previous-blog');
assert.match(fs.readFileSync(path.join(fixture,'badon-site-backups',backups[0],'new-files.txt'),'utf8'),/cara-de-empresa-grande/);
publish();
assert.equal(fs.readFileSync(path.join(fixture,'public_html/blog/cara-de-empresa-grande.html'),'utf8'),html);
assert.equal(fs.readFileSync(path.join(fixture,'public_html/.htaccess'),'utf8'),'routing-sentinel');
assert.equal(fs.readFileSync(path.join(fixture,'public_html/unrelated.html'),'utf8'),'unrelated-sentinel');
console.log('PASS: artigo, âncoras, metadados, CTAs, backup e publicação isolada repetível.');
